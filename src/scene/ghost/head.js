// 귀신 머리: 단위 구를 깎아 얼굴(움푹 꺼진 눈두덩·마른 볼·코·살짝 벌어진 입·각진 턱)을 만들고, 꼭짓점 색으로 그늘을 칠한다.
// 결과는 단위 크기 — 메시의 scale 로 실제 크기(HEAD.size)를 준다. 앞은 +z.
import * as THREE from 'three';
import { smooth } from './loft.js';

// [중심 x, y, z (구 위로 정규화), 퍼짐 x, y, z, 높이] — 단위 구 기준
const SCULPT = [
  [0.33, 0.06, 0.94, 0.17, 0.12, 0.2, -0.15], // 눈두덩 (깊게 꺼짐)
  [-0.33, 0.06, 0.94, 0.17, 0.12, 0.2, -0.15],
  [0.33, 0.29, 0.9, 0.2, 0.06, 0.2, 0.04], // 눈썹뼈
  [-0.33, 0.29, 0.9, 0.2, 0.06, 0.2, 0.04],
  [0, 0.04, 1, 0.035, 0.2, 0.2, 0.11], // 콧대
  [0, -0.24, 1, 0.05, 0.06, 0.2, 0.2], // 코끝
  [0.075, -0.29, 0.97, 0.035, 0.035, 0.2, 0.06], // 콧방울
  [-0.075, -0.29, 0.97, 0.035, 0.035, 0.2, 0.06],
  [0.56, -0.04, 0.82, 0.14, 0.09, 0.2, 0.06], // 광대
  [-0.56, -0.04, 0.82, 0.14, 0.09, 0.2, 0.06],
  [0.5, -0.38, 0.77, 0.13, 0.15, 0.2, -0.1], // 홀쭉한 볼
  [-0.5, -0.38, 0.77, 0.13, 0.15, 0.2, -0.1],
  [0, -0.46, 0.9, 0.16, 0.03, 0.2, 0.02], // 윗입술
  [0, -0.56, 0.85, 0.13, 0.055, 0.2, -0.16], // 힘없이 벌어진 입
  [0, -0.82, 0.58, 0.14, 0.1, 0.2, 0.03], // 턱끝
  [0.97, 0.02, 0.1, 0.07, 0.18, 0.14, 0.09], // 귀
  [-0.97, 0.02, 0.1, 0.07, 0.18, 0.14, 0.09],
  [0.82, 0.25, 0.48, 0.14, 0.14, 0.2, -0.04], // 관자놀이
  [-0.82, 0.25, 0.48, 0.14, 0.14, 0.2, -0.04],
].map(([x, y, z, sx, sy, sz, a]) => {
  const c = new THREE.Vector3(x, y, z).normalize();
  return { c, sx, sy, sz, a };
});

// 그늘 [중심, 퍼짐, 밝기 배율] — 눈 주변은 검게, 입술은 탁한 보랏빛 회색, 입 안은 거의 검정
const SHADE = [
  [[0.33, 0.06, 0.94], [0.19, 0.15, 0.2], [0.12, 0.11, 0.13]],
  [[-0.33, 0.06, 0.94], [0.19, 0.15, 0.2], [0.12, 0.11, 0.13]],
  [[0.33, -0.1, 0.93], [0.13, 0.06, 0.2], [0.55, 0.52, 0.58]], // 눈 밑 다크서클
  [[-0.33, -0.1, 0.93], [0.13, 0.06, 0.2], [0.55, 0.52, 0.58]],
  [[0, -0.57, 0.86], [0.16, 0.12, 0.2], [0.45, 0.42, 0.48]], // 입술·입가
  [[0, -0.56, 0.85], [0.11, 0.045, 0.2], [0.03, 0.025, 0.025]], // 입 안
  [[0.5, -0.38, 0.77], [0.15, 0.17, 0.2], [0.78, 0.78, 0.82]],
  [[-0.5, -0.38, 0.77], [0.15, 0.17, 0.2], [0.78, 0.78, 0.82]],
].map(([c, s, k]) => ({ c: new THREE.Vector3(...c).normalize(), s, k }));

const gauss = (d, c, sx, sy, sz) => {
  const x = (d.x - c.x) / sx;
  const y = (d.y - c.y) / sy;
  const z = (d.z - c.z) / sz;
  return Math.exp(-0.5 * (x * x + y * y + z * z));
};

// 머리카락이 나는 자리인가 (정수리·옆·뒤, 이마 위). 얼굴·귀 아래는 아니다
export function isScalp(d) {
  if (d.y < -0.15) return false;
  if (d.z > 0.35 && d.y < 0.5) return false;
  return true;
}

export function headGeometry() {
  const g = new THREE.SphereGeometry(1, 72, 56);
  const p = g.attributes.position;
  const col = new Float32Array(p.count * 3);
  const d = new THREE.Vector3();
  for (let i = 0; i < p.count; i++) {
    d.fromBufferAttribute(p, i).normalize();
    let r = 1;
    for (const s of SCULPT) r += s.a * gauss(d, s.c, s.sx, s.sy, s.sz);
    let x = d.x * r;
    let y = d.y * r;
    let z = d.z * r;
    x *= 1 - 0.28 * smooth(-0.15, -0.95, d.y); // 아래로 갈수록 좁아지는 턱
    if (d.z < 0) z *= 1 + 0.08 * smooth(0, -0.8, d.z) * smooth(-0.5, 0.3, d.y); // 뒤통수
    if (d.y < -0.55 && d.z > 0.2) z += 0.02 * smooth(-0.55, -0.9, d.y); // 턱이 조금 앞으로
    if (d.y > 0.6) y *= 1.02;
    p.setXYZ(i, x, y, z);
    let k = [1, 1, 1];
    for (const s of SHADE) {
      const w = gauss(d, s.c, s.s[0], s.s[1], s.s[2]);
      k = k.map((v, j) => v * (1 - w + w * s.k[j]));
    }
    if (isScalp(d)) k = [0.07, 0.07, 0.075]; // 머리카락 사이로 보이는 두피 자리는 머리색
    else if (d.y > 0.35 || Math.abs(d.x) > 0.8) { const t = smooth(0.35, 0.5, d.y) * (d.z > 0.35 ? 1 : 0); k = k.map((v) => v * (1 - t * 0.6)); }
    col[i * 3] = k[0];
    col[i * 3 + 1] = k[1];
    col[i * 3 + 2] = k[2];
  }
  g.setAttribute('color', new THREE.BufferAttribute(col, 3));
  g.computeVertexNormals();
  return g;
}

